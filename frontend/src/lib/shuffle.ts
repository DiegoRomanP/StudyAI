/** Fisher-Yates on a copy. */
export function shuffle<T>(items: readonly T[], random: () => number = Math.random): T[] {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

/** mulberry32 seeded by a string hash: the same seed always gives the same sequence. */
function seededRandom(seed: string | number): () => number {
  let state = 2166136261;
  for (const char of String(seed)) state = Math.imul(state ^ char.charCodeAt(0), 16777619);
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Stable mixed order, so a reload or a resumed draft shows the questions in the same order. */
export function seededShuffle<T>(items: readonly T[], seed: string | number): T[] {
  return shuffle(items, seededRandom(seed));
}
